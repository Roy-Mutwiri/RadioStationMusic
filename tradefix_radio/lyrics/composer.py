"""Lyric composition from the topic graph (§13, §14, §15).

ADR-10 — **the words are composed, not generated by a language model.**

Context. §13 requires a LyricsDirector that owns subject selection with historical
awareness, and ACE-Step takes lyrics as *input*, so something has to produce text. §34
lists "lyrics model failure" as a condition the station must survive, implying a model may
exist.

Decision. The default lyric source is a **grammar over this station's own topic graph**,
not an LLM. :class:`LyricComposer` assembles sections from the accurate, pre-hedged
``teaching_points`` and ``phrases`` the topic library already carries.

Why, in order of weight:

1. **§14 becomes enforceable rather than hoped-for.** Every factual statement in a lyric
   is a string an author wrote and marked with a certainty level. An LLM asked to write
   about the dollar/gold relationship will produce "dollar up, gold down" as a flat fact,
   because that is what the training data says — and the §17 validator would then reject
   it, repeatedly, costing a generation cycle each time.
2. **§17's undetectable categories stop mattering.** Copyrighted lyrics and artist
   imitation cannot be detected from text (see :mod:`.validators`). Composing from our own
   corpus means there is no outside text to copy.
3. **Offline, free, instant, deterministic.** No API key, no cost per track, no network
   dependency in the §26 critical path, and a seeded composer is reproducible — which §64
   needs and §101 reporting benefits from.
4. **The fallback exists by construction.** §34's "lyrics model failure" path needs
   something to fall back *to*. Adding an LLM provider later behind the same interface
   makes this composer that fallback, rather than requiring a second one to be written.

Consequence, stated plainly: the lyrics are **more formulaic than a good LLM's**. The
grammar below is built to mitigate that — multiple phrase shapes per section role, pools
of connective lines per narrator perspective, and hooks assembled rather than templated —
but it is a real trade. Accepted because an unattended station that says accurate things
in a slightly repetitive way is better than one that says confident falsehoods about
markets, and §14 is explicit about which risk matters.

**Teaching points are inserted verbatim.** They are not rewritten to match the narrator's
perspective. Naive pronoun substitution produces the exact "generated" register §99 warns
about, and it can change meaning. Perspective instead controls the *connective* lines
around them, which is where a voice actually lives.
"""

