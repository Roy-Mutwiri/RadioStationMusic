def lyrics_director(
    library: ContentLibrary, settings: AppSettings, seed: int = 11
) -> LyricsDirector:
    selector = WeightedSelector(random.Random(seed))
    return LyricsDirector(
        library,
        settings.lyrics,
        DiversityDirector(settings.diversity),
        selector,
    )


def composer(library: ContentLibrary, seed: int = 11) -> LyricComposer:
    return LyricComposer(library, WeightedSelector(random.Random(seed)))


def plan_for(
    library: ContentLibrary,
    settings: AppSettings,
    *,
    seed: int = 11,
    persona_key: str | None = None,
    instrumental: bool = False,
    regime: MarketRegime = MarketRegime.NORMAL_RANGE,
    session: TradingSession = TradingSession.LONDON,
    energy: float = 55.0,
    history: ProgrammingHistory | None = None,
    temperature: float = 1.0,
):
    persona = library.persona(persona_key) if persona_key else None
    style = persona.vocal_styles[0] if persona else VocalStyle.RAP
    return lyrics_director(library, settings, seed).plan(
        history=history or ProgrammingHistory([]),
        regime=regime,
        session=session,
        energy=energy,
        persona=persona,
        vocal_style=style,
        instrumental=instrumental,
        temperature=temperature,
    )


