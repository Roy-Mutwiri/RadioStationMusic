def test_the_hook_is_one_hook_repeated(
    library: ContentLibrary, settings: AppSettings
) -> None:
    """Three different choruses is three verses. A hook is a hook because it returns."""
    for seed in range(60):
        plan = plan_for(library, settings, seed=seed)
        if plan.lyric_format is None:
            continue
        hook_sections = [s for s in plan.lyric_format.sections if "hook" in s or "chorus" in s]
        if len(hook_sections) < 2:
            continue
        composed = composer(library, seed).compose(track_id="TF-1", plan=plan)
        assert composed is not None
        by_section: dict[str, list[str]] = {}
        for line in composed.lyrics.lines:
            by_section.setdefault(line.section, []).append(line.text)
        bodies = [
            tuple(by_section[name]) for name in hook_sections if name in by_section
        ]
        # Brand injection may alter one occurrence, so require a shared core rather than
        # exact equality across all of them.
        if len(bodies) >= 2:
            assert len(set(bodies)) < len(bodies) or any(
                set(bodies[0]) & set(other) for other in bodies[1:]
            ), f"hook sections share no lines: {bodies}"


