def test_topics_rotate_as_history_accumulates(
    library: ContentLibrary, settings: AppSettings
) -> None:
    """§12: repetition checks at several horizons. A fresh roll each time is not enough."""
    director = lyrics_director(library, settings)
    entries: list[HistoryEntry] = []
    chosen: list[str] = []
    for index in range(150):
        plan = director.plan(
            history=ProgrammingHistory(entries),
            regime=MarketRegime.NORMAL_RANGE,
            session=TradingSession.LONDON,
            energy=55.0,
            persona=None,
            vocal_style=VocalStyle.RAP,
            instrumental=False,
        )
        assert plan.topic is not None
        chosen.append(plan.topic.key)
        entries.insert(
            0,
            HistoryEntry(
                track_id=f"TF-{index}",
                genre="deep_house",
                bpm=122,
                musical_key="A minor",
                duration_seconds=210.0,
                is_instrumental=False,
                vocal_style="rap",
                blueprint_signature=f"sig-{index}",
                energy_at_generation=55.0,
                regime_at_generation="normal_range",
                created_at=MOMENT,
                played_at=MOMENT,
                primary_topic=plan.topic.key,
                secondary_topic=plan.secondary.key if plan.secondary else None,
            ),
        )
    counts = Counter(chosen)
    assert len(counts) >= 15, f"only {len(counts)} topics across 150 tracks"
    assert counts.most_common(1)[0][1] / len(chosen) < 0.2
    # No topic twice in a row, which is the one repetition a listener cannot miss.
    assert all(chosen[i] != chosen[i - 1] for i in range(1, len(chosen)))


def test_the_regime_influences_what_the_station_talks_about(
    library: ContentLibrary, settings: AppSettings
) -> None:
    """§1 reaches the lyrics too, not only the music."""
    def topics(regime: MarketRegime) -> Counter[str]:
        return Counter(
            plan_for(library, settings, seed=seed, regime=regime).topic.key  # type: ignore[union-attr]
            for seed in range(90)
        )

    quiet = topics(MarketRegime.QUIET)
    violent = topics(MarketRegime.EXTREME_VOLATILITY)
    quiet_top = {key for key, _ in quiet.most_common(4)}
    violent_top = {key for key, _ in violent.most_common(4)}
    assert quiet_top != violent_top, "the regime has no effect on subject matter"


