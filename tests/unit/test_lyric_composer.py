def test_no_lyric_repeats_a_line_verbatim(
    library: ContentLibrary, settings: AppSettings
) -> None:
    """Outside the hook, a repeated line is a generator looping.

    This is what caught the first deduplication design: deduplicating by line hid a
    looping generator, because the loop's output collapsed to a single line and looked
    clean.
    """
    # Hook and outro sections are excluded via the composer's own role map rather than by
    # guessing at section names. Guessing missed "phrase" — a hook under another name — and
    # reported a hook's deliberate closing refrain as a looping generator. A hook repeats
    # internally by design; that is what makes it a hook.
    from tradefix_radio.lyrics.composer import _ROLE_BY_SECTION

    for seed in range(80):
        plan = plan_for(library, settings, seed=seed)
        composed = composer(library, seed).compose(track_id="TF-1", plan=plan)
        assert composed is not None
        body = [
            line.text
            for line in composed.lyrics.lines
            if _ROLE_BY_SECTION.get(line.section, "body") not in {"hook", "close"}
        ]
        assert len(set(body)) == len(body), f"repeated body line: {body}"


