"""LyricsDirector and LyricComposer (§13, §14, §15, §16, milestones 3.6–3.7).

ADR-10: the words are composed from the station's own topic graph, not generated by a
language model. That decision is what makes §14 testable at all — every factual statement
in a lyric is a string an author wrote and marked with a certainty level — and this module
is where the claim gets checked.

The headline test is at the bottom: compose several hundred lyrics across every format,
persona and topic, and run the §17 validator over all of them. A composer that produces
text the station's own validator rejects is not a working composer, and the acceptance rate
is reported rather than assumed.
"""

