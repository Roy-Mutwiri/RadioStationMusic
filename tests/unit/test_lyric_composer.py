def test_brand_mention_counts_match_the_configured_distribution(
    library: ContentLibrary, settings: AppSettings
) -> None:
    """Milestone 3.8's exit test: the §16 distribution over 1000 draws.

    Checked on **vocal** tracks only. An instrumental track has no lyrics, so its zero is a
    structural fact rather than a draw — and mixing the two made the §3.12 report read
    77/18/5 against a configured 55/35/10 and look like a defect when it was not.

    The tolerance is generous because §95's temperature legitimately sharpens and flattens
    every weighted sample, including this one. What is being verified is that the configured
    weights are the thing being sampled, not that sampling is temperature-free.
    """
    weights = settings.lyrics.tradefix_mention_weights
    director = lyrics_director(library, settings)
    counts: Counter[int] = Counter()
    for index in range(1000):
        plan = director.plan(
            history=ProgrammingHistory([]),
            regime=MarketRegime.NORMAL_RANGE,
            session=TradingSession.LONDON,
            energy=(20.0, 50.0, 80.0)[index % 3],
            persona=None,
            vocal_style=VocalStyle.RAP,
            instrumental=False,
        )
        counts[plan.spec.tradefix_mentions] += 1

    assert set(counts) <= set(weights), f"unconfigured mention counts: {set(counts) - set(weights)}"
    for value, weight in sorted(weights.items()):
        observed = counts[value] / 1000
        assert abs(observed - weight) < 0.15, (
            f"{value} mention(s): configured {weight:.0%}, observed {observed:.1%}"
        )
    # The ordering must hold exactly even where the magnitudes drift.
    by_weight = [value for value, _ in sorted(weights.items(), key=lambda kv: -kv[1])]
    by_observed = [value for value, _ in counts.most_common()]
    assert by_observed == by_weight, f"ordering {by_observed} does not match {by_weight}"


