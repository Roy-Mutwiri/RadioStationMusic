def test_an_uncertain_topic_is_hedged(
    library: ContentLibrary, settings: AppSettings
) -> None:
    """§14: "must never pretend a simplified relationship guarantees price direction"."""
    from tradefix_radio.lyrics.validators import HEDGE_WORDS

    checked = 0
    for key, topic in library.topics.items():
        if not topic.requires_hedging:
            continue
        plan = plan_for(library, settings, seed=hash(key) % 1000)
        # Force the uncertain topic rather than waiting for it to be selected.
        plan = type(plan)(
            spec=plan.spec.model_copy(update={"primary_topic": key}),
            topic=topic,
            secondary=None,
            lyric_format=plan.lyric_format,
            rationale=plan.rationale,
        )
        composed = composer(library, 5).compose(track_id="TF-1", plan=plan)
        assert composed is not None
        text = composed.lyrics.text.lower()
        assert any(word in text for word in HEDGE_WORDS), (
            f"{key} ({topic.certainty}) composed with no hedge:\n{composed.lyrics.text}"
        )
        checked += 1
    assert checked > 5, f"only {checked} hedged topics exercised"


def test_no_lyric_uses_its_topics_own_forbidden_phrases(
    library: ContentLibrary, settings: AppSettings
) -> None:
    """Per-topic overclaims: the thing §14 says that topic specifically must not assert."""
    for seed in range(150):
        plan = plan_for(library, settings, seed=seed)
        composed = composer(library, seed).compose(track_id="TF-1", plan=plan)
        assert composed is not None
        text = composed.lyrics.text.lower()
        for topic in (plan.topic, plan.secondary):
            if topic is None:
                continue
            for phrase in topic.forbidden:
                assert phrase.lower() not in text, (
                    f"{topic.key} forbids {phrase!r}:\n{composed.lyrics.text}"
                )


def test_every_composed_lyric_passes_the_stations_own_validator(
    library: ContentLibrary, settings: AppSettings
) -> None:
    """The headline test, and the reason the composer went through six revisions.

    A composer whose output the station's own §17 validator rejects is not a working
    composer: every rejection costs a generation cycle, and a persistent rejection rate
    means the station eventually runs out of attempts and airs the fallback.

    Started at 75.2% acceptance. The rate is asserted at 100% rather than at a tolerance,
    because the composer draws from a closed, authored corpus — there is no reason for any
    output to be invalid, so any failure here is a real defect rather than noise.
    """
    validator = LyricValidator(settings.lyrics)
    director = lyrics_director(library, settings)
    comp = composer(library)
    entries: list[HistoryEntry] = []
    failures: list[tuple[str, str]] = []
    word_counts: list[int] = []
    composed_count = 0

    personas = list(library.persona_keys)
    for index in range(300):
        persona_key = personas[index % len(personas)]
        persona = library.persona(persona_key)
        energy = (10.0, 35.0, 55.0, 75.0, 95.0)[index % 5]
        plan = director.plan(
            history=ProgrammingHistory(entries),
            regime=list(MarketRegime)[index % len(MarketRegime)],
            session=list(TradingSession)[index % len(TradingSession)],
            energy=energy,
            persona=persona,
            vocal_style=persona.vocal_styles[0],
            instrumental=False,
            temperature=(0.4, 1.0, 1.4)[index % 3],
        )
        composed = comp.compose(track_id=f"TF-{index:05d}", plan=plan, persona=persona)
        assert composed is not None
        composed_count += 1
        word_counts.append(len(composed.lyrics.normalised_text.split()))

        result = validator.validate(
            composed.lyrics,
            ValidationContext(
                primary_topic=plan.topic,
                secondary_topic=plan.secondary,
                expected_mentions=plan.spec.tradefix_mentions,
                format_min_words=plan.lyric_format.min_words if plan.lyric_format else None,
                format_max_words=plan.lyric_format.max_words if plan.lyric_format else None,
            ),
        )
        if not result.accepted:
            failures.append(
                (
                    f"{plan.lyric_format.key if plan.lyric_format else '?'}/{persona_key}",
                    "; ".join(v.detail for v in result.violations),
                )
            )
        assert plan.topic is not None
        entries.insert(
            0,
            HistoryEntry(
                track_id=f"TF-{index:05d}",
                genre=persona.genres[0],
                bpm=120,
                musical_key="A minor",
                duration_seconds=210.0,
                is_instrumental=False,
                vocal_style=persona.vocal_styles[0].value,
                blueprint_signature=f"sig-{index}",
                energy_at_generation=energy,
                regime_at_generation="normal_range",
                created_at=MOMENT,
                played_at=MOMENT,
                primary_topic=plan.topic.key,
                secondary_topic=plan.secondary.key if plan.secondary else None,
                persona_id=persona_key,
            ),
        )

    assert composed_count == 300
    assert not failures, (
        f"{len(failures)}/300 composed lyrics failed the §17 validator; first five:\n"
        + "\n".join(f"  {where}: {why}" for where, why in failures[:5])
    )
    # Word counts span the formats' declared range rather than clustering at one length.
    assert min(word_counts) < 60 < max(word_counts), (
        f"word counts {min(word_counts)}-{max(word_counts)} — the formats are not varying"
    )
